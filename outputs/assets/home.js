  toggle.addEventListener('click', () => toggle.setAttribute('aria-expanded', String(nav.classList.toggle('nav-open'))));
  const input = document.querySelector('#term-search'), results = document.querySelector('#terms');
  const refresh = () => { results.hidden = !input.value.trim() && location.hash !== '#terms'; };
  refresh(); input.addEventListener('input',refresh); window.addEventListener('hashchange',refresh);
  document.querySelector('#categories').addEventListener('click',refresh);
