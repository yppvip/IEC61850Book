  const shell = document.querySelector('.shell');
  if (!catalog || !shell) return;
  document.body.classList.add('has-site-nav', 'home-page');
  const nav = document.createElement('nav');
  nav.className = 'site-nav'; nav.setAttribute('aria-label', '全站导航');
  nav.innerHTML = `<div class="site-nav-utility"><a class="brand" href="#start">IEC 61850 离线知识库</a><div class="site-nav-actions"><a href="#term-search">全局搜索</a><a href="chapters/learning-path.html">学习路线</a></div><button class="nav-toggle" type="button" aria-expanded="false" aria-controls="site-nav-modules">导航</button></div><div class="site-nav-modules" id="site-nav-modules"><div class="site-nav-links"><a class="active" href="#start" aria-current="page">首页</a>${catalog.groups.map(g => `<a href="chapters/${g.entry}">${g.label}</a>`).join('')}</div></div>`;
  document.body.prepend(nav);
  const layout = document.createElement('div'); layout.className = 'home-layout';
  const left = document.createElement('aside'); left.className = 'side-tree'; left.setAttribute('aria-label','知识树');
  left.innerHTML = '<p class="side-title">按学习层次查阅</p><p><a href="chapters/learning-path.html">从编程到电气 · 学习路线 →</a></p>' + catalog.groups.map(g => catalog.tree(g, g.id === 'knowledge' ? 'learning-path.html' : '', 'chapters/')).join('');
