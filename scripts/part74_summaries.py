def revise(name,text):
    if name in SUMMARIES:return SUMMARIES[name]
    # These regular families are summarized consistently from their printed rows.
    if name.startswith('Tdd'):
        scope='相别无关' if name.endswith('Amp') else '相别有关'
        component='偶分量' if 'Evn' in name else '奇分量' if 'Odd' in name else '全部相关分量'
        return f'{scope}电流总需求失真（TDD），{component}；按本版引用的 IEEE 519 定义和需求电流参考读取。'
    if name in ['ThdATmms','ThdVTmms']:
        return ('电流' if name=='ThdATmms' else '电压')+'总谐波/间谐波失真告警延时，单位 ms；与对应 Val 门槛配合。'
    if name in ['ThdAVal','ThdVVal']:
        return ('电流' if name=='ThdAVal' else '电压')+'总谐波/间谐波失真告警门槛，按百分数表示。'
    if name.startswith('Thd'):
        quantity='线电压' if name.endswith('PPV') else '相电压' if name.endswith('PhV') else '电压' if name.endswith('Vol') else '电流'
        scope='相别无关' if name.endswith(('Vol','Amp')) else '相别有关'
        component='偶分量' if 'Evn' in name else '奇分量' if 'Odd' in name else '全部相关分量'
        return f'{scope}{quantity}总谐波/间谐波失真，{component}；计算方法与参考量须明确。'
    return text.replace('己','已').replace('倌号','信号').replace('气休','气体').replace('搡作','操作').replace('瀲活','激活').replace('次數','次数').replace('c各相','C 各相')
